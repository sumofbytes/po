//! The Lucide icons po uses (ISC license, `assets/icons/LICENSE-LUCIDE`), drawn by NSH.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum IconName {
    ArrowUp,
    Calendar,
    CaseSensitive,
    Check,
    ChevronDown,
    ChevronLeft,
    ChevronRight,
    ChevronUp,
    Close,
    CornerDownRight,
    FileText,
    Folder,
    FolderTree,
    GitBranch,
    ListPlus,
    Maximize,
    Minimize,
    PanelLeft,
    Pencil,
    Plus,
    PlusBold,
    Replace,
    Search,
    Settings,
    Square,
    Circle,
    CircleCheck,
    CircleDashed,
    CircleDot,
    CircleHalf,
    CircleX,
    Flag,
    History,
    Layers,
    Lightbulb,
    List,
    Signal,
    SquareKanban,
    Tag,
}

impl IconName {
    pub(crate) fn svg(self) -> (&'static str, &'static [u8]) {
        macro_rules! icon {
            ($name:literal) => {
                (concat!("po-icon-", $name), include_bytes!(concat!("../../assets/icons/", $name, ".svg")))
            };
        }
        match self {
            Self::ArrowUp => icon!("arrow-up"),
            Self::Calendar => icon!("calendar"),
            Self::CaseSensitive => icon!("case-sensitive"),
            Self::Check => icon!("check"),
            Self::ChevronDown => icon!("chevron-down"),
            Self::ChevronLeft => icon!("chevron-left"),
            Self::ChevronRight => icon!("chevron-right"),
            Self::ChevronUp => icon!("chevron-up"),
            Self::Close => icon!("close"),
            Self::CornerDownRight => icon!("corner-down-right"),
            Self::FileText => icon!("file-text"),
            Self::Folder => icon!("folder"),
            Self::FolderTree => icon!("folder-tree"),
            Self::GitBranch => icon!("git-branch"),
            Self::ListPlus => icon!("list-plus"),
            Self::Maximize => icon!("maximize-2"),
            Self::Minimize => icon!("minimize-2"),
            Self::PanelLeft => icon!("panel-left"),
            Self::Pencil => icon!("pencil"),
            Self::Plus => icon!("plus"),
            Self::PlusBold => icon!("plus-bold"),
            Self::Replace => icon!("replace"),
            Self::Search => icon!("search"),
            Self::Settings => icon!("settings"),
            Self::Square => icon!("square"),
            Self::Circle => icon!("circle"),
            Self::CircleCheck => icon!("circle-check"),
            Self::CircleDashed => icon!("circle-dashed"),
            Self::CircleDot => icon!("circle-dot"),
            Self::CircleHalf => icon!("circle-half"),
            Self::CircleX => icon!("circle-x"),
            Self::Flag => icon!("flag"),
            Self::History => icon!("history"),
            Self::Layers => icon!("layers"),
            Self::Lightbulb => icon!("lightbulb"),
            Self::List => icon!("list"),
            Self::Signal => icon!("signal"),
            Self::SquareKanban => icon!("square-kanban"),
            Self::Tag => icon!("tag"),
        }
    }
}
